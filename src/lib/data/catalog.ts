/** Elements from the AU/degree form catalogues publish, phased by time of perihelion. */
function heliocentric(opts: {
  aAu: number; e: number; iDeg: number; omDeg: number; wDeg: number;
  /** Julian Date of perihelion passage. */
  tp: number;
}): Elements {
  const a = opts.aAu * AU_KM;
  // M = n(t − Tp); at the epoch we choose (Tp itself) the mean anomaly is zero, so store
  // the elements with epoch = Tp and m0 = 0. Works for closed and open orbits alike.
  return {
    a,
    e: opts.e,
    i: opts.iDeg * DEG,
    om: opts.omDeg * DEG,
    w: opts.wDeg * DEG,
    m0: 0,
    epoch: opts.tp,
    mu: GM.sun,
  };
}

/** A conic whose shape is published but whose phase is not known offline. */
function unphased(opts: { aAu: number; e: number; iDeg: number; omDeg: number; wDeg: number }): Elements {
  return heliocentric({ ...opts, tp: 2451545.0 });
}

/** Elements for a satellite of a planet, given in km and degrees. */
function satellite(opts: {
  aKm: number; e: number; iDeg: number; omDeg: number; wDeg: number; m0Deg: number;
  epoch: number; mu: number;
}): Elements {
  return elementsFromDegrees(opts);
}

const jdOf = (iso: string): number => new Date(iso).getTime() / 86400000 + 2440587.5;

/**
 * Radius of the sphere of influence, km: r = a·(m/M)^(2/5) (Laplace).
 * `a` is the body's semi-major axis about its parent and m/M the mass ratio.
 */
function soi(aKm: number, muBody: number, muParent: number): number {
  return aKm * Math.pow(muBody / muParent, 0.4);
}

