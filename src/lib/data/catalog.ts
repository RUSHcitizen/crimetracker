function smallBodyObjects(): SpaceObject[] {
  return SMALL_BODIES.map((b) => {
    const shape = { aAu: b.aAu, e: b.e, iDeg: b.iDeg, omDeg: b.omDeg, wDeg: b.wDeg };
    const phased = b.tp !== undefined;
    const elements = phased ? heliocentric({ ...shape, tp: jdOf(b.tp!) }) : unphased(shape);
    const obj: SpaceObject = {
      id: b.id,
      name: b.name,
      subtitle: b.subtitle,
      kind: b.kind,
      parent: 'sun',
      color: b.color,
      weight: b.weight,
      provenance: phased
        ? P_SMALL_BODY
        : {
            ...P_SMALL_BODY,
            accuracy: 'Orbit shape is published and accurate. Position along the orbit is NOT known offline and is not shown.',
            limitations: 'This build ships the orbit only. The object is placed on it once a live epoch is retrieved from the JPL Small-Body Database.',
          },
      ephemeris: phased ? { kind: 'elements', elements } : { kind: 'elements-unphased', elements },
      tags: ['small-body', b.kind],
      facts: b.facts.map(([label, value]) => ({ label, value })),
    };
    if (b.radiusKm !== undefined) obj.radiusKm = b.radiusKm;
    if (b.status !== undefined) obj.status = b.status;
    if (!phased) obj.phaseUnknown = true;
    return obj;
  });
}

